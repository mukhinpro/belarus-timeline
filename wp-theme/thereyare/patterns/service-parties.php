<!-- wp:details {"summary":"How long should I book for?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How long should I book for?</summary><!-- wp:paragraph -->
<p>Two hours covers most parties: half an hour before guests arrive for the room and the setup, then the arrival, the activity and the cake. Three hours if there is an entertainer or a long meal. We would rather you booked two and added an hour on the day than paid for time nobody used.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can other parents get the photographs of their children?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can other parents get the photographs of their children?</summary><!-- wp:paragraph -->
<p>Yes. You get one gallery link to pass around, and every parent can download the full-resolution files of their own child. It is the part guests remember, and it costs nothing extra.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What if a guest's parents do not want their child photographed?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What if a guest's parents do not want their child photographed?</summary><!-- wp:paragraph -->
<p>Tell us on arrival and that child is not photographed, or is only photographed from behind. It happens at maybe one party in ten and it is never a problem. Nothing from a party is ever published without asking you first, and we do not publish other people's children at all.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Is a park or a venue harder than a house?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Is a park or a venue harder than a house?</summary><!-- wp:paragraph -->
<p>Easier, usually — more light and more room to stand back. Indoor play centres are the hard one: low ceilings, coloured lighting and no daylight. We can shoot them, and we bring lighting, but tell us in advance so we arrive set up for it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How quickly do we get the photographs?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How quickly do we get the photographs?</summary><!-- wp:paragraph -->
<p>Within a week, which is deliberate — a party gallery that arrives a month later has missed the moment when everyone wanted to see it. Two or three go to you the same evening.</p>
