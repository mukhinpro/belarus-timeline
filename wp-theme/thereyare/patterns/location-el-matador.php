<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--50)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Getting there</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The lot is off Pacific Coast Highway at 32350 PCH, signposted for El Matador State Beach. It holds about twenty cars and costs a few dollars in coins or by card. When it is full, people park on the shoulder of PCH — legal, but walk on the inland side with children.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>From the lot it is a steep staircase and a short scramble down to the sand. There is no bathroom and no shade. Best for families whose youngest is about five or older; for a baby or a toddler, <a href="/locations/santa-monica/">Santa Monica</a> or <a href="/locations/arroyo-seco-pasadena/">Arroyo Seco</a> will give you a better hour.</p>
<!-- /wp:paragraph --></section>
<!-- /wp:group -->

<!-- wp:group {"tagName":"section","style":{"spacing":{"margin":{"top":"var:preset|spacing|50"}}},"layout":{"type":"constrained"}} -->
<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--50)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What to wear here</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Long dresses and loose fabric, because there is almost always wind and it does good things in a photograph. Deep blues, rust and cream against the wet sand. Bare feet — bring shoes for the stairs and leave them at the bottom. Nothing white in the last half hour of sun, when the sand throws light back up.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Sessions here are the standard <a href="/family-photography-los-angeles/">family session</a> price, with no travel charge — Malibu is inside our thirty miles.</p>
<!-- /wp:paragraph --></section>
