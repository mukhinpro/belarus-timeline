<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--60)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">When to come</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Ninety minutes before sunset, no later. The staircase down takes ten minutes with small children, the small lot fills early, and the light that makes this place worth the drive lasts about twenty minutes. Arriving an hour before sunset means photographing in a queue.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Check the tide before you commit.</strong> At high tide half the beach and most of the arches are underwater. We check it when we set the date, and we will move the session rather than shoot a tide that does not work.</p>
<!-- /wp:paragraph --></section>
<!-- /wp:group -->

