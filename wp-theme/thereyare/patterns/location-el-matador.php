<!-- wp:details {"summary":"Do you need a permit to photograph at El Matador?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Do you need a permit to photograph at El Matador?</summary><!-- wp:paragraph -->
<p>Not for a family session. El Matador is a California state beach, and personal photography with handheld equipment is fine. Permits are for commercial shoots with crews, lighting stands and props. We bring a camera and nothing that needs a permit.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Is it crowded?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Is it crowded?</summary><!-- wp:paragraph -->
<p>At sunset on a weekend, yes — there can be four other photographers on the same stretch. Weekdays are a different beach entirely. If your schedule allows a Tuesday, take it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can we get down there with a stroller?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can we get down there with a stroller?</summary><!-- wp:paragraph -->
<p>No. It is a steep staircase with a rocky last section. A baby carrier works; a stroller does not. That is the main reason we suggest somewhere else for families with a baby.</p>
