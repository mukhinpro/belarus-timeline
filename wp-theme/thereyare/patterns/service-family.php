<!-- wp:details {"summary":"How much does a family photo session cost in Los Angeles?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How much does a family photo session cost in Los Angeles?</summary><!-- wp:paragraph -->
<p>Ours is $800 for two hours, with twelve fully retouched photographs and around fifty more graded. Across Los Angeles family sessions run from about $350 to well over $2,000; the spread is mostly in session length and how many finished images are included, so compare those two numbers rather than the headline price.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How long does a family session take?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How long does a family session take?</summary><!-- wp:paragraph -->
<p>Two hours, and the length is deliberate. The first twenty minutes are usually children deciding we are safe; the good frames come after that. A forty-minute session with small children is a session of children being polite.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Should we shoot at home or outdoors?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Should we shoot at home or outdoors?</summary><!-- wp:paragraph -->
<p>With a child under six, at home, almost every time — familiar rooms, no drive, naps still possible, and the pictures look like your life rather than a location. With older children, outdoors gives more variety and better movement. We are happy to do half and half if you live near somewhere good.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can grandparents, cousins and the dog be in the photographs?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can grandparents, cousins and the dog be in the photographs?</summary><!-- wp:paragraph -->
<p>Yes, at no extra charge. Tell us in advance so we plan the time — a dog needs one adult who is not in every frame, and extended family usually wants a few groupings of their own while everyone is dressed and in one place.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"When will we see the photographs?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>When will we see the photographs?</summary><!-- wp:paragraph -->
<p>A first look within a few days and the finished gallery in about two weeks. If the photographs are for a card or a gift with a date attached, say so when you book and we will work to it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What should we wear?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What should we wear?</summary><!-- wp:paragraph -->
