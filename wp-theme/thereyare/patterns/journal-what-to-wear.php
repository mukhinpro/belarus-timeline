<p class="has-dim-color has-text-color has-large-font-size">The question we get more than any other, usually two days before the session, usually at eleven at night. Here is the whole answer, so you can stop scrolling.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Coordinate, don't match</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Five people in identical white shirts and blue jeans is the single most common family-photo mistake, and it comes from good intentions. Matching flattens everyone into one shape. Coordinating keeps five people looking like five people who happen to belong together.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The method that works: pick three or four colours that sit near each other — say oatmeal, rust, deep olive and cream — and dress everyone from that set. Nobody wears the same thing. One person can carry a pattern, and it should be the person you want the eye to land on.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Colours that photograph well in Los Angeles</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Warm neutrals and muted earth tones, almost always. They sit well against dry grass, sandstone, eucalyptus and evening light, which is most of what we shoot against here. Deep blues and forest greens work beautifully at the beach.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>What to avoid: neon anything, because it bounces colour up onto faces and everyone turns slightly green. Bright white in full sun, because it blows out before skin does. And pure black on a sunny day, which reads as a hole in the picture.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Dressing children</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Comfort beats everything. A child in a scratchy collar will spend the hour pulling at it, and that is what the photographs will show. Let them wear something they already like, in a colour from your set. Bring one spare outfit per child under six — not because they will change looks, but because something will get spilled.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Shoes matter more than people expect, because children get carried and photographed from below. Boots or clean sneakers, not light-up trainers with a cartoon on the side.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">A short list to leave at home</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Logos and slogans. In ten years you will see the brand, not the child.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Busy patterns on more than one person.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Anything bought that week that nobody has worn yet.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Sunglasses on heads, hair ties on wrists — small things that date a picture.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

