<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--50)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Parking and timing</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Free street parking on Fern Dell Drive if you arrive before about four in the afternoon; after that it fills with people walking up to the observatory. The Fern Dell lot itself is small. We usually meet at the picnic tables at the bottom of Fern Dell — flat, shaded, and easy to find.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Bathrooms at the Fern Dell entrance. Flat paths for the first ten minutes, which means a stroller works if you want it to.</p>
<!-- /wp:paragraph --></section>
