<!-- wp:details {"summary":"Do I need a permit for family photos in Griffith Park?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Do I need a permit for family photos in Griffith Park?</summary><!-- wp:paragraph -->
<p>Not for a handheld family session on public paths. Los Angeles Recreation and Parks requires a permit for commercial shoots with crew and equipment setups; a photographer with a camera and a family is not that. If a session ever needs lighting stands, we handle the permit ourselves.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can we photograph at the observatory?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can we photograph at the observatory?</summary><!-- wp:paragraph -->
<p>We can, and we will if you want that skyline. Be aware that at sunset you are sharing the lawn with several hundred people and half a dozen other photographers, and it shows in the background. The hillsides ten minutes below give better light and no crowd.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Is it too hot in summer?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Is it too hot in summer?</summary><!-- wp:paragraph -->
<p>On the hillsides in July, yes, until about six in the evening. Fern Dell stays ten degrees cooler under the trees and is our summer answer for families who do not want to wait for sunset.</p>
