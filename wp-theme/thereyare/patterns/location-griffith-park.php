<h2 class="wp-block-heading">Two very different parks</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p><strong>Fern Dell</strong> is the shaded end: sycamores, a stream, ferns, and dappled light that stays workable through the middle of the day. This is where we take families with a baby or a toddler, and where we go when the rest of the city is too hot.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>The hillsides above it</strong> are the opposite — dry golden grass, open sky, and in the last hour of light a backlit haze that makes the whole frame glow. Ten minutes uphill on a fire road, easy for anyone who can walk it, and there is usually nobody there.</p>
<!-- /wp:paragraph --></section>
<!-- /wp:group -->

