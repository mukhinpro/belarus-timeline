<!-- wp:details {"summary":"How much does a wedding photographer cost in Los Angeles?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How much does a wedding photographer cost in Los Angeles?</summary><!-- wp:paragraph -->
<p>Ours starts at $1,600 for four hours with two photographers. Across Los Angeles wedding coverage runs from about $1,500 to $10,000 and beyond. The two things that move the number are hours and whether there is a second photographer — a single photographer cannot be with you and in the room at the same time, which is why ours are always a pair.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How many hours do we need?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How many hours do we need?</summary><!-- wp:paragraph -->
<p>Four covers a ceremony, portraits and the first part of the reception. Six to eight covers a full day from getting ready to the dancing. Send us the running order and we will tell you honestly what you need, including when the answer is less than you were about to book.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Do you do posed group photographs?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Do you do posed group photographs?</summary><!-- wp:paragraph -->
<p>Yes, and we are quick about it. Send a list of the groupings that matter and we will get through them in twenty minutes rather than an hour — the family photographs are for your parents, and the rest of the day is for you.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What happens if you are ill on the day?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What happens if you are ill on the day?</summary><!-- wp:paragraph -->
<p>There are two of us at every wedding, so the day is covered even if one of us cannot make it. If neither could, we would find you a photographer from the group we work with and refund the difference. It has not happened, and the plan exists anyway.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"When do we get the photographs?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>When do we get the photographs?</summary><!-- wp:paragraph -->
<p>A preview set within a week, and the full gallery in six to eight weeks. Weddings take longer than a family session because there are ten times as many frames to sort before the editing begins.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

