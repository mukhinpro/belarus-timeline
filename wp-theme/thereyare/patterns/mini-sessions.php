<!-- wp:details {"summary":"What is a mini session?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What is a mini session?</summary><!-- wp:paragraph -->
<p>A short family session on a fixed day at a fixed place, with several families booked one after another. Twenty minutes each, one setup, one look. The saving comes from sharing the setup and the travel between ten families rather than from doing less careful work.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How is it different from a full session?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How is it different from a full session?</summary><!-- wp:paragraph -->
<p>A full family session is two hours, at a place and time we choose together, with room to move around, change outfits and let a slow child warm up. You get 12 retouched images and about 50 graded. A mini is one setup, one outfit, 8 images, and the clock is real.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"When are the next dates?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>When are the next dates?</summary><!-- wp:paragraph -->
<p>We run mini days in spring and then in October and November for card season. Dates are announced here and to the mailing list about six weeks ahead, and slots usually go within the week.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What if it rains on the day?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What if it rains on the day?</summary><!-- wp:paragraph -->
<p>The whole day moves to the rain date, which is set when the slots are announced, and your slot time moves with it. If you cannot make the rain date, the payment goes towards a full session instead.</p>
