<h2 class="wp-block-heading" style="margin-bottom:var(--wp--preset--spacing--40)">Questions about getting ready</h2>
<!-- /wp:heading -->

<!-- wp:details {"summary":"How do I prepare for a family photo session?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How do I prepare for a family photo session?</summary><!-- wp:paragraph -->
<p>Book around your children's naps, coordinate clothes in three or four related colours without matching outfits, bring snacks and a spare outfit, and feed everyone before you arrive. That covers almost all of it. Send us a photograph of the clothes laid out the week before and we will tell you what to swap.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What if my child will not cooperate?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What if my child will not cooperate?</summary><!-- wp:paragraph -->
<p>That is a normal session, not a failed one. We never ask children to pose — we give them something to do and photograph what happens around it. If there is a meltdown we keep working; the frames right after a cry, when a child is holding onto a parent, are often the best of the day.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What time of day is best for photos?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What time of day is best for photos?</summary><!-- wp:paragraph -->
<p>The ninety minutes before sunset, or the hour after sunrise. Midday is the one to avoid outdoors — the sun is overhead, eyes fall into shadow and everyone squints. Indoors and at home we can work at any hour.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What happens if it rains?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What happens if it rains?</summary><!-- wp:paragraph -->
<p>We move the date at no cost, and we decide together the morning of rather than days ahead — Los Angeles forecasts are wrong more often than they are right. Overcast is not rain, incidentally: a grey sky is the softest light of the year and we will happily shoot in it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can grandparents or pets join the session?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can grandparents or pets join the session?</summary><!-- wp:paragraph -->
<p>Yes to both, at no extra charge for a family session. Tell us in advance so we plan the time — a dog needs one person who is not in every frame, and grandparents usually want a few portraits of their own while everyone is dressed.</p>
<!-- /wp:paragraph --></details>
