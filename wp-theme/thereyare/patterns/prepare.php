<!-- wp:paragraph {"textColor":"dim","fontSize":"large"} -->
<p class="has-dim-color has-text-color has-large-font-size">Everything worth doing in the week before a family session, and a few things worth not doing. Most of it is about timing and sleep. None of it is about anybody looking different than they do.</p>
<!-- /wp:paragraph -->

<!-- wp:group {"tagName":"section","style":{"spacing":{"margin":{"top":"var:preset|spacing|60"}}},"layout":{"type":"constrained"}} -->
<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--60)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Pick the time around your children, not the light</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We will find good light at almost any hour. What we cannot fix is a session booked over a nap. Tell us your children's nap and meal times before we choose a slot, and we will build the session around them. For most families that means an hour after the morning nap, or the ninety minutes before sunset with an early dinner first.</p>
<!-- /wp:paragraph --></section>
<!-- /wp:group -->

<!-- wp:group {"tagName":"section","style":{"spacing":{"margin":{"top":"var:preset|spacing|50"}}},"layout":{"type":"constrained"}} -->
<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--50)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The week before</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Clothes.</strong> Lay everything out on a bed and send us a photograph. We answer every one of these, and it takes two minutes. Coordinate colours, do not match outfits — the <a href="/journal/">journal</a> has the long version.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Haircuts</strong> at least five days out, so they settle. Never the day before.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Nothing new on skin.</strong> No first-time facial, no new product. A reaction takes a week to fade — exactly the week you do not have.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Tell the children</strong> what is happening, in a sentence. Small children handle a plan much better than a surprise with a stranger in it.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></section>
<!-- /wp:group -->

<!-- wp:group {"tagName":"section","style":{"spacing":{"margin":{"top":"var:preset|spacing|50"}}},"layout":{"type":"constrained"}} -->
<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--50)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What to bring</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Snacks that do not stain or crumble. Nothing red, nothing chocolate.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Water for everyone, adults included.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>A spare outfit for every child under six, and wipes.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>One familiar object — a blanket, a toy, a book. It ends up in a few frames and it is usually the picture you keep.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>A hairbrush and hair ties, off wrists before we start.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></section>
<!-- /wp:group -->

<!-- wp:group {"tagName":"section","style":{"spacing":{"margin":{"top":"var:preset|spacing|50"}}},"layout":{"type":"constrained"}} -->
<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--50)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">On the day</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Arrive ten minutes early if you can, so nobody starts the session out of breath. Feed everyone beforehand. Expect the first ten minutes to produce nothing — that is the children deciding we are safe, and it is time we have already budgeted for.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>And the single most useful thing you can do: stop watching the camera. Look at each other. Children copy whichever adult is nearest, and every good family photograph comes from that.</p>
<!-- /wp:paragraph --></section>
<!-- /wp:group -->

