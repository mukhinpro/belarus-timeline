<!-- wp:details {"summary":"When should newborn photos be taken?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>When should newborn photos be taken?</summary><!-- wp:paragraph -->
<p>Posed studio newborn work has to happen in the first ten days, while a baby still curls. Because we do not pose, our window is much wider — anywhere from the first week to about eight weeks. Most families book us for somewhere around two to three weeks, when everyone has stopped being quite so shell-shocked.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Should I book before the baby arrives?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Should I book before the baby arrives?</summary><!-- wp:paragraph -->
<p>Yes, around the due date rather than on it. We hold a loose two-week window and you text us when the baby comes. No deposit is lost if the timing moves, because the timing always moves.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Does my house need to be tidy?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Does my house need to be tidy?</summary><!-- wp:paragraph -->
<p>No. We photograph one corner of one room and we move what needs moving ourselves. Nobody with a two-week-old should be cleaning for a photographer, and a house that looks lived in is the point rather than a problem.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can our older child and the dog be in the photographs?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can our older child and the dog be in the photographs?</summary><!-- wp:paragraph -->
<p>Please. A first meeting between a toddler and a new sibling is the strongest set of frames in most newborn sessions, and it only exists once. We photograph the older child first, while they still have patience.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How much does newborn photography cost in Los Angeles?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How much does newborn photography cost in Los Angeles?</summary><!-- wp:paragraph -->
<p>Ours is $700 for a two-hour session at your home, with twelve retouched photographs and around fifty more graded. Across Los Angeles newborn sessions run from about $400 to well over $2,000; posed studio work sits at the higher end because it takes a specialist and a studio full of equipment.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

