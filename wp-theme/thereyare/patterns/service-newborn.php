<h2 class="wp-block-heading">Lifestyle, not props</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We do not do the posed studio newborn work — no baskets, no headbands, no baby balanced on a folded blanket. Those photographs are beautiful and they are somebody else's specialism. What we photograph is the actual first month: the bed you have not made, the way your partner holds the baby's head, an older sibling deciding what to make of all this.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>It means nothing is asked of the baby, which is why the session works at three days old or at six weeks. It also means the pictures still look right in fifteen years, when the props would have dated.</p>
