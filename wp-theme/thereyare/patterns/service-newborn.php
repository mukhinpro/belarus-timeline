<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>All we need is one room with a window. We bring lighting for the rest of the house. Nobody has to tidy — genuinely, we will move what needs moving and the corner of the room we photograph is a corner you have chosen.</p>
