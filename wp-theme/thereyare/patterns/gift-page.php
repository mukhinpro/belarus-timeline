<!-- wp:details {"summary":"Does the certificate expire?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Does the certificate expire?</summary><!-- wp:paragraph -->
<p>No, and it legally cannot. California prohibits selling a gift certificate with an expiry date, so ours simply do not have one. Use it this month or in three years — a new baby, a birthday, a free Saturday.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What if the session they want costs more than the certificate?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What if the session they want costs more than the certificate?</summary><!-- wp:paragraph -->
<p>They pay the difference when they book, and we tell them the exact figure before anything is confirmed. A certificate for an amount works like a deposit towards any session.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"And if the session costs less?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>And if the session costs less?</summary><!-- wp:paragraph -->
<p>The balance stays on the certificate for next time. If less than fifteen dollars is left, California law lets them ask for it back in cash, and we will hand it over without a fuss.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can I give it as a surprise, without a date arranged?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can I give it as a surprise, without a date arranged?</summary><!-- wp:paragraph -->
<p>That is how most of them are given. Nothing is booked until the person holding the certificate gets in touch, so there is no diary to coordinate behind their back.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"I need it tonight. How fast can you send it?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>I need it tonight. How fast can you send it?</summary><!-- wp:paragraph -->
<p>Buy it and then text or email us — we will send the PDF straight away rather than waiting until the morning. Gifts are usually bought the night before, and we plan for that.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can it be transferred to someone else?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can it be transferred to someone else?</summary><!-- wp:paragraph -->
<p>Yes. Whoever holds the code can book with it. Tell us the new name and we will reissue the PDF so it reads properly.</p>
