<details class="wp-block-details tya-faq-item"><summary>I really do not photograph well.</summary><!-- wp:paragraph -->
<p>Almost nobody photographs well in a snapshot taken from below in a kitchen at seven in the evening, which is the evidence most people are going on. Given proper light, some direction and ninety minutes, that changes. It is our half of the job and you do not have to arrive knowing how to pose.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Is this only for mothers?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Is this only for mothers?</summary><!-- wp:paragraph -->
<p>No. Fathers are the group most likely to have no photograph of themselves with their children at all, and a growing share of these sessions are booked for or by them. The page is named for the search term, not for the people it is for.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Should my children be in the photographs?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Should my children be in the photographs?</summary><!-- wp:paragraph -->
<p>Do both. We start with you alone while you still have the room to yourself, then bring the children in for the second half. The portraits people frame are usually from the second half; the ones they are glad to have twenty years later are often from the first.</p>
<!-- /wp:paragraph --></details>
