<!-- wp:details {"summary":"Is this a headshot session?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Is this a headshot session?</summary><!-- wp:paragraph -->
<p>No, though you will end up with something that works as one. A headshot is made to a casting or corporate brief and is judged against it. This is made for you, and it is judged by whether it looks like you at your best. Different intent, different session, and usually a much better photograph.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What should I wear?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What should I wear?</summary><!-- wp:paragraph -->
<p>Two or three things you already feel good in, in solid colours. A well-cut shirt beats something new and stiff every time. Bring more than you think you need and we choose together in the room with the light on.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How much retouching do you do?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How much retouching do you do?</summary><!-- wp:paragraph -->
<p>By hand, and lightly. Temporary things go — a blemish, a stray hair, a crease in a collar. Permanent things stay unless you ask: lines, scars, grey. The aim is a photograph you recognise as yourself on a very good day, not a stranger.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Why not just book a family session?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Why not just book a family session?</summary><!-- wp:paragraph -->
<p>Because in a family session you are one of five people and the photographs are about the group. This is two hours where the only subject is you, which sounds indulgent and is the reason it works. If you want both, book the family session and add this — we will run them on the same day.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

