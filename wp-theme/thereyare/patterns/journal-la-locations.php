<p class="has-dim-color has-text-color has-large-font-size">Six places we shoot families in Los Angeles, what each one is actually like, and when to arrive. Parking included, because in this city that is half the decision.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">El Matador, Malibu</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The sea caves and rock arches everyone has seen. It earns the reputation, and it punishes bad timing. Arrive ninety minutes before sunset: the small lot fills, the staircase down takes ten minutes with children, and the good light lasts about twenty minutes. Check the tide before you commit — at high tide half the beach is gone. Best for families with children over about five, because of the stairs.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Griffith Park</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Everyone shoots at the observatory, which is why we do not. The park is four thousand acres, and the dry-grass hillsides off Fern Dell in the late afternoon give golden backlight with nobody in the frame. Free parking on the side streets if you come before four. Good for every age, and the shortest drive for most of the east side.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The Venice canals</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Footbridges, water, front gardens that people actually tend. It photographs like a small European town dropped into the west side. Parking is the whole problem: allow twenty minutes, and go on a weekday. The light is best about an hour before sunset when it comes down the water. Not for a child who runs, because there are no railings.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Arroyo Seco, Pasadena</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Old sycamores and oaks, which give something the beach cannot: shade with structure in it. This is where we go when a family wants photographs that do not look like California postcards, or when the coast is fogged in. Easy parking, flat paths, works with a stroller. Our first suggestion for newborns and for grandparents.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Santa Monica, north of the pier</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Less dramatic than Malibu and far more practical: paid lots right on the sand, bathrooms, a flat walk from the car. If you have a toddler and a baby, this is the beach to choose. Go on a weekday — the same stretch on a Saturday is a different location entirely.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Your own home</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The one people dismiss and then love. Nobody has to be driven anywhere, nap times are not a problem, and the pictures are of your actual life rather than a nice place you visited once. All we need is a room with a window. We bring the lighting, and there is no travel charge inside thirty miles of Los Angeles.</p>
