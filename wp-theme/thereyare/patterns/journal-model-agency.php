<p class="has-dim-color has-text-color has-large-font-size">Los Angeles agencies see thousands of submissions. Most are rejected in seconds, and usually for reasons that have nothing to do with the child. Here is what they are actually looking at.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Agencies want digitals, not a portfolio</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>This is the mistake that costs parents the most money. A first submission does not need retouched, styled, artistic photographs. It needs digitals: plain clothes, plain background, natural light, no makeup, hair down and off the face. A head-and-shoulders, a three-quarter, a full length, and a profile. That is it.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The reason is simple. An agent needs to see the child, and heavy styling hides exactly what they are assessing. A glossy portfolio submitted cold often reads as a parent who has been sold something, which is not the first impression you want.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What they are actually assessing</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Ease in front of a camera.</strong> Not beauty. Whether the child looks comfortable and present, or braced.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Range.</strong> Two or three genuinely different expressions across the set. A single smile repeated four times says nothing.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Current accuracy.</strong> Photographs from six months ago are useless for a growing child. Under ten, digitals age out in about three months.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Whether the parent will be easy to work with.</strong> Yes, really. A clear email with correctly sized files says a great deal.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">How to submit</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Almost every legitimate Los Angeles agency has a submission form on its own website. Use it. Include the child's name, date of birth, current height and weight, the city you live in, and the four digitals. Nothing else — no biography, no list of school plays.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Submit to several agencies at once. That is normal at this stage and nobody minds.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The warning worth reading twice</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A legitimate agency takes a commission when your child works. It does not charge a registration fee, it does not require you to buy a portfolio from a photographer it names, and it does not run a paid "training course" before signing anyone. Any of those three is the signal to walk away, and in California an agency charging advance fees is on the wrong side of the law.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>You will also need a work permit from the California Department of Industrial Relations before your child can be paid for a job, and a Coogan trust account. The agency will walk you through both once you are signed.</p>
<!-- /wp:paragraph -->

