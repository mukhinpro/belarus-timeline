<!-- wp:details {"summary":"What is the difference between digitals and a portfolio?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What is the difference between digitals and a portfolio?</summary><!-- wp:paragraph -->
<p>Digitals are plain: no makeup, plain background, hair down, four or five angles. They exist so an agent can see the child accurately. A portfolio is styled work that shows range, and it is what an agency asks for after signing. Submitting a styled portfolio cold is the most common and most expensive mistake.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How often do digitals need redoing?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>How often do digitals need redoing?</summary><!-- wp:paragraph -->
<p>Under ten, about every three months — children change fast and out-of-date digitals waste an agent's time and yours. Teenagers, twice a year. This is why we keep the session cheap enough to repeat and do not sell an expensive package that ages out in a season.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Do you retouch these?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Do you retouch these?</summary><!-- wp:paragraph -->
<p>Barely, and deliberately. Colour and exposure, nothing else. An agency rejects a submission where the skin has been smoothed, because they cannot tell what they are looking at. Honest skin is the requirement, not a shortcut.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

