<p class="has-dim-color has-text-color has-large-font-size">Parents apologise to us about their two-year-old roughly once a week. Nobody needs to. Here is how a session with a small child actually goes, and the three decisions that make it go well.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The time of day decides almost everything</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A session booked over a nap is a session with a crying child, and no amount of skill fixes tired. We would rather move a shoot by two hours than fight a schedule. Tell us when your child naps and eats before we pick a time, not after.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>For most families with a child under four, this means an hour after the morning nap, or the ninety minutes before sunset with an early dinner beforehand. Both give us good light and a child who is awake and fed, which is the whole game.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">We do not ask children to pose</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A posed toddler produces exactly one expression, and every parent recognises it: the tight, obedient not-quite-smile. So we do not ask. We give them something to do — walk to that tree, whisper a secret to your dad, count the birds — and photograph what happens around the task.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>This is why our sessions look like people doing things rather than people arranged in a row. It is also why the first ten minutes usually produce nothing usable, and we plan for that.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">If they cry, we keep working</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Every parent tenses when a child melts down in front of a stranger with a camera. Please do not. A two-minute cry into a parent's shoulder is normal, and the frames just after it are often the best of the session — the child is calm, holding on, and looking at you rather than at us.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>What does not help is a rushed bribe or a raised voice. Pick them up, walk twenty steps away, and come back when they are ready. We have the time; it is built into the booking.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What to bring</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Snacks that do not stain and do not crumble. Not chocolate, not anything red.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Water for everyone, including the adults.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>One familiar object — a blanket, a toy, a book. It appears in three frames and it is worth it.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>A spare outfit, and wipes.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">And the one thing that helps most</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Stop watching the camera. Children copy the nearest adult, and a parent glancing anxiously at the photographer produces a child glancing anxiously at the photographer. Look at your own family instead. Everything good in a family photograph comes from that.</p>
<!-- /wp:paragraph -->

