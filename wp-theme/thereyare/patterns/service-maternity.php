<details class="wp-block-details tya-faq-item"><summary>When should I have maternity photos taken?</summary><!-- wp:paragraph -->
<p>Thirty to thirty-four weeks for most people. Earlier than about twenty-eight and the shape does not read in a photograph; much past thirty-six and comfort becomes the limit. If you are expecting twins, move the whole window forward by three or four weeks.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

