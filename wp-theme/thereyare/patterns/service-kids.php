<h2 class="wp-block-heading" style="margin-bottom:var(--wp--preset--spacing--40)">Questions about children's portraits</h2>
<!-- /wp:heading -->

<!-- wp:details {"summary":"My child is shy. Will this work?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>My child is shy. Will this work?</summary><!-- wp:paragraph -->
<p>Shy children often photograph better than confident ones, because they are not performing. We spend the first stretch of the session not photographing at all, and we never ask a child to look at the camera and smile. Somewhere in the second half they stop noticing us, and that is where the portrait is.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can I be in the room?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can I be in the room?</summary><!-- wp:paragraph -->
<p>Always, and with a young child you should be. With a teenager, ask them — many are noticeably more themselves with a parent reading a book in the corner rather than watching, and some would rather you were in the car. Either is fine.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What age is this for?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>What age is this for?</summary><!-- wp:paragraph -->
<p>Roughly three to eighteen. Under three, a <a href="/family-photography-los-angeles/">family session</a> at home usually gives more, because a toddler photographed alone for two hours is a short session with a long invoice.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Do you photograph siblings together?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Do you photograph siblings together?</summary><!-- wp:paragraph -->
<p>Yes, and the same price covers up to three children. Sibling frames are usually the ones parents order large, so we always shoot both — each child alone, and then together.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can we use the photographs for a school or agency application?","className":"tya-faq-item"} -->
<details class="wp-block-details tya-faq-item"><summary>Can we use the photographs for a school or agency application?</summary><!-- wp:paragraph -->
<p>Yes — you get print-resolution files and the crops those applications ask for. If the purpose is an agency specifically, read the <a href="/journal/">journal note on how child agencies work</a> first. A first submission usually needs plain digitals rather than portraits, and we would rather tell you that than sell you a session you do not need yet.</p>
