<p class="has-ash-color has-text-color has-large-font-size">The question I am asked most, and the one with the least complicated answer. Wear what you already feel good in. Here is what that means in practice.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Start in your own wardrobe</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Almost everyone's first instinct is to buy something for the session. Almost everyone regrets it on the day: the new thing does not quite fit, or it fits but does not feel like them, and the discomfort is visible in every frame. The pieces that photograph best are the ones that have already earned their place — the shirt you reach for when nobody is coming over, the lingerie you actually wear rather than the set kept for occasions.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Bring more than you need. Four or five options is right; we will use three. Choosing together in the room, with the light on, works far better than deciding at home.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The three looks that always work</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p><strong>A shirt.</strong> White, black, or a man's shirt borrowed from someone. Buttoned to wherever you like. It is the most requested look in boudoir for a reason: it hides and reveals at exactly the rate you choose, and it does not date.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Something knitted.</strong> An oversized sweater, a cardigan, a wrap. Soft light on soft fabric and skin — it reads as a Sunday morning, and the pictures feel like a memory rather than a shoot.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>One set of lingerie.</strong> One, not four. A single set in a colour that suits you, that fits properly — straps that do not dig, a band that sits flat. Fit matters more than price by a wide margin. Black and skin tones photograph most reliably; red and jewel tones can be beautiful under the right light, so bring one if you love it.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What to leave at home</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Anything with a visible logo or slogan.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Busy prints. They fight the light and pull the eye from the person.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Tight elastic. Waistbands and bra straps leave marks that take an hour to fade — arrive in loose clothes.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Costumes. Nurses, cats, schoolgirls. Not because of judgement — because they turn a portrait of you into a portrait of a costume.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Shoes, jewellery and the one thing with meaning</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Heels change posture and are worth bringing even if they only appear in three frames. Jewellery: less, and one piece that is yours. And if there is an object with a story — a ring, a partner's watch, the shoes from the wedding — bring it. It gives the session a reason, and the reason shows.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The short version, once more: wear what you already love, bring more than you need, and let us choose in the room. The rest is light, and that is my job. There is a fuller list on the <a href="/prepare-for-your-session/">preparation page</a>, and the <a href="/boudoir-photography-los-angeles/">session page</a> covers what the day itself is like.</p>
