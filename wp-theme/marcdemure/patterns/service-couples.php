<details class="wp-block-details"><summary>What is a couples boudoir session?</summary><!-- wp:paragraph -->
<p>An intimate portrait session for two people together, in a bedroom or a studio, dressed as much or as little as you both choose. It is closer to a documentary of how you are with each other than to a posed shoot, and the pictures are for you — most couples never publish a single one.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Is it awkward with a photographer in the room?"} -->
<details class="wp-block-details"><summary>Is it awkward with a photographer in the room?</summary><!-- wp:paragraph -->
<p>For about ten minutes, then it is not. I work quietly, keep direction to a few words, and shoot on a longer lens so I am not standing over you. Couples who were nervous at the start almost always say afterwards that they forgot I was there — which is exactly when the good frames happen.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

