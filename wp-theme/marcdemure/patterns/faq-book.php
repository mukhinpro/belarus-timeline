<details class="wp-block-details"><summary>How far ahead should I book a boudoir session?</summary><!-- wp:paragraph -->
<p>Two to four weeks is usual. If the pictures are for a date — a wedding, an anniversary, a birthday — allow six to eight weeks so the gallery and any prints arrive in time. Weekday sessions are easier to find than weekends.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How does the deposit work?"} -->
<details class="wp-block-details"><summary>How does the deposit work?</summary><!-- wp:paragraph -->
<p>A deposit of $200 holds your date and comes off the total. The balance is due on the day of the session. If you move the date with at least a week's notice the deposit moves with it; with less notice it covers the studio booking that was made for you.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What happens after I send the form?"} -->
<details class="wp-block-details"><summary>What happens after I send the form?</summary><!-- wp:paragraph -->
<p>I reply within a day, usually the same one, with two or three dates and a short note on what to bring. Nothing is booked until you have said yes to a date and the deposit is paid, so sending the form commits you to nothing.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Do you travel outside Los Angeles?"} -->
<details class="wp-block-details"><summary>Do you travel outside Los Angeles?</summary><!-- wp:paragraph -->
<p>Yes. Anywhere within thirty miles of Los Angeles carries no travel charge. Further — Orange County, Santa Barbara, Palm Springs, San Diego — is quoted as one flat figure before you commit to anything.</p>
