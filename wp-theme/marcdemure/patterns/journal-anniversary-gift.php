<p class="has-ash-color has-text-color has-large-font-size">Roughly half the sessions I photograph are gifts. Here is how the good ones are given, and the one way it goes wrong.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The album on the anniversary</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The classic. One partner books a session for themselves, in secret, a couple of months before the date. The album arrives the week before, wrapped. It is opened after dinner. I have been told about the opening enough times to say with confidence that it lands, every time, and that the person receiving it usually says the same thing: that they had no idea.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Timing: book eight weeks out, shoot five to six weeks out, and the album is in your hands with a week to spare. The <a href="/albums/">small book</a> is the one most often given this way — it fits in a coat pocket and a hand.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The wedding morning</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A tradition with its own page: <a href="/bridal-boudoir-los-angeles/">bridal boudoir</a>. The bride shoots in the weeks before, and the album goes to the groom the morning of the wedding, often carried over by the best man. There is a version for grooms too, which is less talked about and just as good.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Giving the session, not the pictures</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The other direction: buying a session for someone else, as a <a href="/gift-certificates/">gift certificate</a>. It works when the giver is close — a partner, a sister, the friends of a bride. The recipient books their own date, privately, and decides everything about the session including whether it happens. The giver never hears about it unless they are told. That privacy is part of the gift, and I keep it absolutely.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>There is no expiry on the certificate, by California law, so the pressure of "you have to use it by June" does not exist. Some people book within a week. Some wait a year for the right moment. Both are fine.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The one way it goes wrong</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>When the gift comes with an expectation. A session bought by a partner who then wants to choose the outfits, or see the gallery first, or asks for "more than she usually would". I decline those, politely and without exception, and I say so here so that it is understood in advance: the person in front of the camera decides everything. A gift that comes with conditions is not one.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Giving it to yourself</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The third kind of gift, and the one that has grown most. After a divorce, after a diagnosis, after a year of training, at forty or fifty or sixty. Nobody is receiving the album but you. Those sessions are often the best in the calendar, because there is nobody to impress and nothing to hide from, and it shows.</p>
<!-- /wp:paragraph -->
