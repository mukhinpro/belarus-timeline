<!-- wp:details {"summary":"How much does a boudoir photoshoot cost in Los Angeles?"} -->
<details class="wp-block-details"><summary>How much does a boudoir photoshoot cost in Los Angeles?</summary><!-- wp:paragraph -->
<p>Sessions here start at $650 for two hours, with fifteen fully retouched photographs and around sixty more with colour grading included. Studio rental, if we use one, is billed at cost on top, typically $100 to $250 for the session. Across Los Angeles, boudoir sessions range from about $400 to well over $2,000; the difference is usually in how many finished images are included and whether retouching is done by hand.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What should I wear to a boudoir shoot?"} -->
<details class="wp-block-details"><summary>What should I wear to a boudoir shoot?</summary><!-- wp:paragraph -->
<p>Two or three things you already feel good in. A well-fitting shirt, a favourite sweater, a set of lingerie you actually wear — these photograph better than anything bought for the occasion. Bring more than you think you need and we choose together. I send a short list once a date is booked, and you are welcome to ignore all of it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"I am not a model and I am not twenty-five. Is boudoir still for me?"} -->
<details class="wp-block-details"><summary>I am not a model and I am not twenty-five. Is boudoir still for me?</summary><!-- wp:paragraph -->
<p>Most of the women I photograph are between thirty and sixty, and almost none have been in front of a camera like this before. Being photogenic is not something a person has; it is light, direction and someone telling you what to do with your hands. That is my side of the work. Every body is photographed as it is, and every body is retouched with the same restraint.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Do you retouch the photographs?"} -->
<details class="wp-block-details"><summary>Do you retouch the photographs?</summary><!-- wp:paragraph -->
<p>Yes, by hand, and lightly. Temporary things go — a blemish, a bruise, a stray hair. Permanent things stay unless you ask: scars, stretch marks, tattoos, the shape you actually have. The aim is a photograph you recognise as yourself on a very good day, not a stranger.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can I do a bridal boudoir session before my wedding?"} -->
<details class="wp-block-details"><summary>Can I do a bridal boudoir session before my wedding?</summary><!-- wp:paragraph -->
<p>Bridal boudoir is a large part of what I shoot. Book six to eight weeks before the wedding so the gallery and any album arrive in time. If the pictures are a gift for your partner, tell me the date and I will work backwards from it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Will anyone else see my photographs?"} -->
<details class="wp-block-details"><summary>Will anyone else see my photographs?</summary><!-- wp:paragraph -->
<p>Not unless you sign a release naming the specific images that may be shown, and you can withdraw that release later without giving a reason. The default is that nothing is published. Your gallery is private and password protected, originals are stored encrypted, and files are deleted ninety days after delivery unless you ask me to keep them.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can I bring a friend to the session?"} -->
<details class="wp-block-details"><summary>Can I bring a friend to the session?</summary><!-- wp:paragraph -->
<p>Yes, and many people do. A friend in the room usually makes the first half hour easier, and by the second half most people have forgotten they are there.</p>
