<p class="has-ash-color has-text-color has-large-font-size">How to prepare for a boudoir shoot, day by day, from someone who has watched what helps and what quietly ruins a morning. Most of it is about rest. None of it is about a diet.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Seven days out: stop changing things</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>This is the week to do nothing new. No new skincare, no first-time facial, no experimental hair colour. Anything your skin has not met before can react, and a reaction takes about a week to fade — the exact week you do not have. Hair colour or a cut should be done by now, so it settles. If you are planning to wax, do it two days before, not the morning of.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Four days out: skip the tan</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Spray tan is the single most common regret. It looks fine in a bathroom mirror and orange under studio light, and it streaks at the elbows and knees where nobody checked. Your own skin tone is the one the light was set up for. If you have a real tan from the summer, that is different — that photographs beautifully.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Two days out: hands</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Hands are in almost every frame of a boudoir session — on a collar, in hair, against a wall. A manicure is worth more than any other single preparation. Clean, shaped, bare or one neutral colour. Chipped polish is the one thing retouching can never make elegant; it can only remove it, which takes an hour a frame.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The night before: sleep, water, nothing else</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Sleep shows more in a photograph than anything, and no retouching truly replaces it. Drink water through the day. Go easy on wine and salt — both puff the face by morning. Lay out what you are bringing so the morning has no decisions in it. If nerves are keeping you up, that is normal, and worth knowing that the first twenty minutes of the session are just talking.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The morning: eat, and arrive in loose clothes</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A normal breakfast. People who skip eating to look flatter arrive shaky and cold, and it shows in the shoulders before it shows anywhere else. Wear loose clothes — no tight waistband, no bra for the drive if you can manage it — because elastic marks take an hour to fade and we would rather spend that hour shooting. Then come in, sit down, and let the first twenty minutes be a conversation.</p>
<!-- /wp:paragraph -->

