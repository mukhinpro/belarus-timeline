<h2 class="wp-block-heading" style="margin-bottom:var(--wp--preset--spacing--40)">What people ask first.</h2>
<!-- /wp:heading -->

<!-- wp:details {"summary":"I am not photogenic. Really."} -->
<details class="wp-block-details"><summary>I am not photogenic. Really.</summary><!-- wp:paragraph -->
<p>Everyone says this, including people you would assume never think it. Being photogenic is not a property of a face — it is direction, light and a photographer who tells you what to do with your hands. That is my half of the work, and you do not have to arrive knowing how to pose.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How much do I have to take off?"} -->
<details class="wp-block-details"><summary>How much do I have to take off?</summary><!-- wp:paragraph -->
<p>Exactly as much as you decide, and you can decide during the session rather than before it. Plenty of sessions never go past a shirt and good light. We agree the line beforehand and I do not push it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Who else is in the room?"} -->
<details class="wp-block-details"><summary>Who else is in the room?</summary><!-- wp:paragraph -->
<p>Me, and anyone you bring. No assistant unless you ask for one. If having a friend there makes it easier, bring the friend — it usually helps.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Will my photographs end up online?"} -->
<details class="wp-block-details"><summary>Will my photographs end up online?</summary><!-- wp:paragraph -->
<p>Only if you sign a release saying which specific images may be used, and you can withdraw it later without giving a reason. The default is that nothing is published. Most sessions are never published, and that is fine.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What should I bring?"} -->
<details class="wp-block-details"><summary>What should I bring?</summary><!-- wp:paragraph -->
<p>Two or three things you already feel good in, whatever they are. A shirt that fits well beats expensive lingerie that does not. I send a short list once a date is booked, and you are welcome to ignore all of it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How long until I see them?"} -->
<details class="wp-block-details"><summary>How long until I see them?</summary><!-- wp:paragraph -->
<p>A first look within a few days, the finished gallery in about two weeks. If it is a gift with a date attached, say so when booking and I will work to it.</p>
<!-- /wp:paragraph --></details>
