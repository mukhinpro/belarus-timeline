<!-- wp:details {"summary":"Is boudoir photography for men a real thing?"} -->
<details class="wp-block-details"><summary>Is boudoir photography for men a real thing?</summary><!-- wp:paragraph -->
<p>Yes, and a growing share of what I shoot. The pictures are usually a gift for a partner, a marker after a big change — a divorce, a diagnosis, a year of training — or simply the first honest portrait a man has had made of himself as an adult. The name is borrowed from the women's genre, but the approach is its own.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Do I need to be in shape?"} -->
<details class="wp-block-details"><summary>Do I need to be in shape?</summary><!-- wp:paragraph -->
<p>No. Lighting does more for a body than a gym ever has, and I have photographed men across every size and every decade from the twenties to the seventies. Hard light and shadow give any shape definition. Retouching stays light — temporary things go, the man himself stays.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What do men wear for a boudoir shoot?"} -->
<details class="wp-block-details"><summary>What do men wear for a boudoir shoot?</summary><!-- wp:paragraph -->
<p>Whatever you would wear on a good evening: a well-cut shirt, a plain white tee, dark jeans, a suit if that is you. Underwear you actually own, in a colour without a logo. Bring a few options and we work through them. Costumes and props are not needed and usually get in the way.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

