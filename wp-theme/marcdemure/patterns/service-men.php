<details class="wp-block-details"><summary>How much does a men's boudoir session cost in Los Angeles?</summary><!-- wp:paragraph -->
<p>From $650 for two hours, with fifteen fully retouched images and about sixty more with colour grading. Studio rental, when we use one, is added at cost. A deposit holds the date and the balance is due on the day.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

