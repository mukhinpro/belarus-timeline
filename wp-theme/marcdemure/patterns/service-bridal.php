<h2 class="wp-block-heading" style="margin-bottom:var(--wp--preset--spacing--40)">Questions about bridal boudoir</h2>
<!-- /wp:heading -->

<!-- wp:details {"summary":"When should I do a bridal boudoir shoot?"} -->
<details class="wp-block-details"><summary>When should I do a bridal boudoir shoot?</summary><!-- wp:paragraph -->
<p>Five to six weeks before the wedding. Early enough that the album is in your hands a week before the day, late enough that your hair and skin are how they will be at the wedding. Book about eight weeks out to get that window.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What do you wear for bridal boudoir?"} -->
<details class="wp-block-details"><summary>What do you wear for bridal boudoir?</summary><!-- wp:paragraph -->
<p>The classic set is the veil, the wedding-day lingerie and the shoes. A white shirt — his, if you like — with the ring. And one thing that is just you, nothing bridal at all. Three looks in two hours is about right.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How much does bridal boudoir cost in Los Angeles?"} -->
<details class="wp-block-details"><summary>How much does bridal boudoir cost in Los Angeles?</summary><!-- wp:paragraph -->
<p>Here, $650 for the session with fifteen retouched images, plus an album from $390 if you want one for the gift. Across Los Angeles, bridal boudoir runs from about $500 to over $2,500; the spread is mostly in how many finished images are included and whether an album is part of it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can my bridesmaids book it for me as a gift?"} -->
<details class="wp-block-details"><summary>Can my bridesmaids book it for me as a gift?</summary><!-- wp:paragraph -->
<p>Yes — that is what the <a href="/gift-certificates/">gift certificates</a> are for. They buy the session, you book the date privately and decide everything about it. Nobody who gave the gift hears anything about the session unless you tell them.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Will the photographs be shown anywhere?"} -->
<details class="wp-block-details"><summary>Will the photographs be shown anywhere?</summary><!-- wp:paragraph -->
<p>Not unless you sign a release for specific images, which you can withdraw later. Bridal sessions are almost never published, and that is the expectation going in.</p>
