<h2 class="wp-block-heading">Why brides book this</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Partly for the gift — an album handed over on the wedding morning, or the night before, is a tradition for good reason. And partly for themselves: the months before a wedding are spent being looked at, measured and photographed for other people. A boudoir session is two hours where the only person you are dressing for is you.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The veil, the shoes, the ring, the something-borrowed all come along if you want them. Or none of it — a white shirt and morning light is the most requested look, and it is the one that dates least.</p>
