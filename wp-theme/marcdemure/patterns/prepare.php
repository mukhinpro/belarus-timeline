<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--70)"><!-- wp:heading {"level":2,"style":{"spacing":{"margin":{"bottom":"var:preset|spacing|40"}}}} -->
<h2 class="wp-block-heading" style="margin-bottom:var(--wp--preset--spacing--40)">Questions about getting ready</h2>
<!-- /wp:heading -->

<!-- wp:details {"summary":"Should I lose weight before a boudoir shoot?"} -->
<details class="wp-block-details"><summary>Should I lose weight before a boudoir shoot?</summary><!-- wp:paragraph -->
<p>No. Crash dieting the week before makes skin dull and energy low, and it shows more than the two pounds ever would. Come as you are. Light, angle and direction do what a diet cannot, and the photographs are of you, not of a version of you that lasted one week.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"How should I prepare for a boudoir session if I am nervous?"} -->
<details class="wp-block-details"><summary>How should I prepare for a boudoir session if I am nervous?</summary><!-- wp:paragraph -->
<p>Everyone is, so the session is built for it: twenty minutes of talking before a camera appears, short runs of a few minutes, and the back of the camera shown to you between them. Bring a friend if it helps. By the third run most people have stopped thinking about it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What if I get my period on the day?"} -->
<details class="wp-block-details"><summary>What if I get my period on the day?</summary><!-- wp:paragraph -->
<p>Tell me, and we either shoot around it — most poses and outfits are unaffected — or move the date at no cost. Both happen regularly and neither is a problem.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Can I eat before the session?"} -->
<details class="wp-block-details"><summary>Can I eat before the session?</summary><!-- wp:paragraph -->
<p>Yes, please do — a normal meal an hour or two before. People who skip eating to look flatter arrive shaky and cold, and it shows in the shoulders. There is water and coffee in the room.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details --></section>
