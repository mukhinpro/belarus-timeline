<!-- wp:paragraph {"textColor":"ash","fontSize":"large"} -->
<p class="has-ash-color has-text-color has-large-font-size">Everything worth doing in the week before a boudoir session, and a few things worth not doing. Most of it is about arriving rested. None of it is about losing weight.</p>
<!-- /wp:paragraph -->

<!-- wp:group {"tagName":"section","style":{"spacing":{"margin":{"top":"var:preset|spacing|60"}}},"layout":{"type":"constrained"}} -->
<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--60)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The week before</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Skin.</strong> No new products, no peels, no first-time treatments. Anything you have not used before can react, and a reaction takes a week to fade. Moisturise as usual.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Hair.</strong> Colour or cut at least five days out, so it settles. Do not try a new style for the session.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Tan.</strong> Skip spray tan. It photographs orange under studio light and streaks where it never showed in the mirror. Your own skin tone is the right one.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Nails.</strong> Hands are in almost every frame. Clean, shaped, and either bare or one neutral colour. Chipped polish is the one thing retouching cannot make elegant.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Waxing or shaving.</strong> Two days before, not the day of, so any redness is gone.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></section>
<!-- /wp:group -->

<!-- wp:group {"tagName":"section","style":{"spacing":{"margin":{"top":"var:preset|spacing|50"}}},"layout":{"type":"constrained"}} -->
<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--50)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">The night before</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Sleep. It is the single thing that shows most in a photograph and the only one no amount of retouching truly fixes. Drink water through the day, go easy on alcohol and salt — both puff the face by morning — and lay out what you are bringing so the morning is calm.</p>
<!-- /wp:paragraph --></section>
<!-- /wp:group -->

<!-- wp:group {"tagName":"section","style":{"spacing":{"margin":{"top":"var:preset|spacing|50"}}},"layout":{"type":"constrained"}} -->
<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--50)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What to bring</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Three or four outfits you already feel good in. A well-fitting shirt, a favourite sweater, lingerie you actually wear. More than you think you need; we choose together.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>One thing with meaning, if there is one — a partner's shirt, a piece of jewellery, a pair of shoes. It gives the session a story.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Loose clothes to arrive in. Tight waistbands and bra straps leave marks that take an hour to fade.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Your own makeup for touch-ups, and a lip colour you like.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>A playlist, if music helps you settle. The room has a speaker.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></section>
<!-- /wp:group -->

<!-- wp:group {"tagName":"section","style":{"spacing":{"margin":{"top":"var:preset|spacing|50"}}},"layout":{"type":"constrained"}} -->
<section class="wp-block-group" style="margin-top:var(--wp--preset--spacing--50)"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Hair and makeup</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Both are fine: come as you are, or book a stylist for the morning. If you book one, ask for a look that is a little more than your everyday and a little less than an evening out — studio light is kinder than a phone camera, and heavy makeup reads heavier still. I work with two stylists who know what photographs well and can put you in touch.</p>
<!-- /wp:paragraph --></section>
<!-- /wp:group -->

