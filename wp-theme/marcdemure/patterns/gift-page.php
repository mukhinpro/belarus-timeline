<!-- wp:details {"summary":"Is a boudoir session an appropriate gift?"} -->
<details class="wp-block-details"><summary>Is a boudoir session an appropriate gift?</summary><!-- wp:paragraph -->
<p>It is one of the best, when it comes from the right person. From a partner, from close friends before a wedding, from a sister after a divorce — yes. From a colleague, no. The certificate is deliberately quiet about what it is for, and the recipient decides everything about the session, including whether it happens at all.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Does the certificate expire?"} -->
<details class="wp-block-details"><summary>Does the certificate expire?</summary><!-- wp:paragraph -->
<p>No, and it legally cannot. California prohibits selling a gift certificate with an expiry date, so ours simply do not have one. Use it this month or in three years.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"What if they want a different session than the one I chose?"} -->
<details class="wp-block-details"><summary>What if they want a different session than the one I chose?</summary><!-- wp:paragraph -->
<p>The certificate's value goes towards whatever they book. Choosing a session just makes the gift read well on paper. If the session they want costs more, they pay the difference; if less, the balance stays on the code for an album or a next time.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"Will you tell me when they book?"} -->
<details class="wp-block-details"><summary>Will you tell me when they book?</summary><!-- wp:paragraph -->
<p>No. Once the certificate is given, everything about the session — whether it is booked, when, and what the photographs look like — belongs to the person holding it. That is part of what you are giving.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"summary":"I need it tonight."} -->
<details class="wp-block-details"><summary>I need it tonight.</summary><!-- wp:paragraph -->
<p>Buy it and then text or email me — I will send the PDF straight away rather than in the morning. Gifts are usually bought the night before, and I plan for that.</p>
<!-- /wp:paragraph --></details>
