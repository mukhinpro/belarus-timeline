<h2 class="wp-block-heading">The terms, plainly</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>You are eighteen or older, and you show government ID on the day. No exceptions, no embarrassment — it is the law and it protects you too.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>The session costs you nothing, and you receive ten retouched images for your own use.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>You sign a release for a specific list of images, chosen together after the session — not for everything shot. They may appear in the public portfolio and in the paid member area.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>You can withdraw the release at any time by email. The images come down the same day, everywhere I control. What has already been printed or seen cannot be recalled, and I say that here so it is not a surprise later.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>How far the session goes is agreed before it starts and does not move during it. "Nude" on the day means what we wrote down the week before.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Bring someone if you want to. Many people do.</li>
<!-- /wp:list-item --></ul>
