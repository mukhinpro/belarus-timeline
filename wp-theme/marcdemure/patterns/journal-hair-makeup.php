<p class="has-ash-color has-text-color has-large-font-size">Half my clients book a stylist for the morning. Half come as they are. Both look right in the pictures, so the question is really about what kind of morning you want.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What studio light actually does to makeup</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Studio light is kinder than a phone camera and much kinder than a bathroom mirror. Skin reads smoother, colour reads richer, and small imperfections vanish in the falloff. The consequence is that makeup done for the mirror reads heavier in the photograph — foundation sits visibly, contouring shows as stripes, and a dark lip becomes the whole picture.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>So the rule for boudoir makeup is: a little more than your everyday, a little less than a night out. Skin that looks like skin, defined brows, mascara, a lip colour you like. That is almost always enough.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">When a stylist is worth it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Not for the makeup, mostly. For the morning. An hour in a chair with someone doing your hair is the best possible transition from a normal day into a session — you arrive already looked after, already slowed down, and the first ten minutes of nerves are simply gone. If you are the kind of person who finds it relaxing, book it. I work with two stylists who know what photographs well and will put you in touch.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">When to skip it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>If you never wear much makeup, do not start on the day of a portrait. The photographs are meant to look like you, and a face you do not recognise is the one outcome nobody wants. Come with your own routine, bring the products for a touch-up, and let the light do the rest. The same goes for hair: a style you have never worn will feel like a costume, and feel is visible.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Hair, specifically</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Down, with some movement in it, photographs better than anything set. Waves that were slept in are perfect. Very straight, very flat hair can read severe under a hard key light; a little volume at the root fixes it. Colour or cut at least five days before, so it settles, and never a new colour the week of the session.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">For men</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A haircut a week out, a shave or a deliberate beard trim the day before, and a moisturiser in the morning so skin does not read dry under the light. That is the whole list. Nobody has ever needed more.</p>
